export type Dict = typeof dict.ar

/** Resolve a dot-path inside a nested dictionary with a safe fallback. */
function resolve(d: Record<string, unknown>, path: string): string | undefined {
  let node: unknown = d
  for (const key of path.split('.')) {
    if (node && typeof node === 'object' && key in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[key]
    } else {
      return undefined
    }
  }
  return typeof node === 'string' ? node : undefined
}

/** Resolve a dot-path and return the raw node (string or string[]). */
function resolveRaw(d: Record<string, unknown>, path: string): unknown {
  let node: unknown = d
  for (const key of path.split('.')) {
    if (node && typeof node === 'object' && key in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[key]
    } else {
      return undefined
    }
  }
  return node
}

export interface I18n {
  t: (key: string) => string
  /** Resolves array-valued keys (e.g. split headline lines). */
  tArr: (key: string) => string[]
  lang: Lang
  dir: 'rtl' | 'ltr'
}

/** Client hook — reads the active language from the existing Settings context. */
export function useI18n(): I18n {
  const { language } = useSettings()
  const lang: Lang = language === 'en' ? 'en' : 'ar'

  const t = useCallback(
    (key: string): string => {
      const table = lang === 'en' ? dict.en : dict.ar
      return resolve(table as unknown as Record<string, unknown>, key) ?? key
    },
    [lang],
  )

  const tArr = useCallback(
    (key: string): string[] => {
      const table = lang === 'en' ? dict.en : dict.ar
      const node = resolveRaw(table as unknown as Record<string, unknown>, key)
      return Array.isArray(node) ? (node as string[]) : [String(node ?? key)]
    },
    [lang],
  )

  return { t, tArr, lang, dir: lang === 'ar' ? 'rtl' : 'ltr' }
}
